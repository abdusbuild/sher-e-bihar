# Regenerates app/data/images.js (size + tiny blur preview of every photo in public/images).
# Run after adding or replacing photos:  python scripts/image-meta.py
import base64, glob, io, json, os
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
meta = {}
for f in sorted(glob.glob(os.path.join(root, "public", "images", "*.*"))):
    if not f.lower().endswith((".jpg", ".jpeg", ".png", ".webp")):
        continue
    im = Image.open(f).convert("RGB")
    w, h = im.size
    tiny = im.resize((16, max(1, round(16 * h / w))), Image.LANCZOS)
    buf = io.BytesIO()
    tiny.save(buf, "JPEG", quality=60)
    meta["/images/" + os.path.basename(f)] = {
        "width": w,
        "height": h,
        "blur": "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode(),
    }

out = os.path.join(root, "app", "data", "images.js")
with open(out, "w", encoding="utf-8") as fh:
    fh.write("// Generated by scripts/image-meta.py: do not edit by hand.\n")
    fh.write("export const imageMeta = " + json.dumps(meta, indent=2) + ";\n")
print(f"wrote {len(meta)} images to {out}")
